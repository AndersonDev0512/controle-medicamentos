def icon(name: str, size: int = 22) -> str:
    return f'<i class="ui-ico ui-ico-{name}" style="width:{size}px;height:{size}px" aria-hidden="true"></i>'


@lru_cache(maxsize=1)
def icon_css() -> str:
    svgs = {
        nome: (
            '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="black" '
            f'stroke-width="2" stroke-linecap="round" stroke-linejoin="round">{corpo}</svg>'
        )
        for nome, corpo in ICONS.items()
    }
    # SVGs do kit (assets/icons) têm prioridade. Na máscara só importa o alfa, então
    # currentColor vira preto.
    svgs.update({nome: svg.replace("currentColor", "black") for nome, svg in icones_svg().items()})
    regras = [
        ".ui-ico{display:inline-block;flex:none;vertical-align:middle;background-color:currentColor;"
        "-webkit-mask:var(--ico) center/contain no-repeat;mask:var(--ico) center/contain no-repeat;}"
    ]
    for nome, svg in svgs.items():
        regras.append(f'.ui-ico-{nome}{{--ico:url("data:image/svg+xml,{quote(svg)}");}}')
    return "\n".join(regras)
